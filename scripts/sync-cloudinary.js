async function sync() {
  console.log(`Fetching images from Cloudinary (folder: ${folder})...`);
  const auth = Buffer.from(`${apiKey}:${apiSecret}`).toString('base64');
  
  // Use Search API for sorted images in the folder
  const searchUrl = `https://api.cloudinary.com/v1_1/${cloudName}/resources/search`;
  const res = await fetch(searchUrl, {
    method: 'POST',
    headers: {
      'Authorization': `Basic ${auth}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      expression: `folder:${folder}/* OR folder:${folder} AND resource_type:image`,
      max_results: 500,
      sort_by: [{ "created_at": "asc" }]
    })
  });

  const data = await res.json();
  let resources = data.resources || [];

  // Fallback to by_asset_folder if search expression found fewer
  if (resources.length === 0) {
    const folderUrl = `https://api.cloudinary.com/v1_1/${cloudName}/resources/by_asset_folder?asset_folder=${folder}&max_results=500`;
    const folderRes = await fetch(folderUrl, {
      headers: { 'Authorization': `Basic ${auth}` }
    });
    const folderData = await folderRes.json();
    resources = (folderData.resources || []).filter(r => r.resource_type === 'image');
  }

  console.log(`Found ${resources.length} image(s) in Cloudinary.`);

  const items = resources.map((r, i) => {
    const preset = romanticPresets[i % romanticPresets.length];
    // Optimized URL with auto format (webp/avif/jpeg), auto quality, and width capping
    const src = `https://res.cloudinary.com/${cloudName}/image/upload/f_auto,q_auto,w_1000,c_limit/${r.public_id}`;
    return {
      src,
      alt: preset.alt,
      title: preset.title,
      subtitle: preset.subtitle,
      publicId: r.public_id
    };
  });

  const outDir = path.join(rootDir, 'src', 'data');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const outPath = path.join(outDir, 'galleryImages.js');
  const fileContent = `// Auto-generated by scripts/sync-cloudinary.js
// Cloudinary images from folder "${folder}" (${items.length} images)

export const galleryItems = ${JSON.stringify(items, null, 2)};

export default galleryItems;
`;

  fs.writeFileSync(outPath, fileContent, 'utf-8');
  console.log(`Successfully generated ${outPath} with ${items.length} items!`);
}

sync().catch(err => {
  console.error('Sync failed:', err);
  process.exit(1);
});
